/**
 * Regenerates src/assets/logos.ts from the simple-icons package.
 *
 *   cd frontend && node scripts/gen-logos.cjs
 *
 * Icons are bundled locally so the app never fetches a logo at runtime.
 * simple-icons is CC0-1.0; the marks themselves remain trademarks of their owners.
 */
const fs = require('fs')
const path = require('path')
const si = require('simple-icons')

// candidate id -> simple-icons export name
const MAP = {
  // simple-icons' macOS mark is a wordmark, which reads poorly at tile size;
  // the Apple mark is the recognisable one.
  macos: 'siApple',
  freebsd: 'siFreebsd',
  openbsd: 'siOpenbsd',
  netbsd: 'siNetbsd',
  ubuntu: 'siUbuntu',
  'linux-mint': 'siLinuxmint',
  'pop-os': 'siPopos',
  'zorin-os': 'siZorin',
  'elementary-os': 'siElementary',
  kubuntu: 'siKubuntu',
  xubuntu: 'siXubuntu',
  lubuntu: 'siLubuntu',
  'ubuntu-mate': 'siUbuntumate',
  'kde-neon': 'siKde',
  deepin: 'siDeepin',
  'mx-linux': 'siMxlinux',
  debian: 'siDebian',
  'fedora-workstation': 'siFedora',
  'fedora-silverblue': 'siFedora',
  'fedora-kinoite': 'siFedora',
  'opensuse-leap': 'siOpensuse',
  'opensuse-tumbleweed': 'siOpensuse',
  'opensuse-microos': 'siOpensuse',
  solus: 'siSolus',
  manjaro: 'siManjaro',
  slackware: 'siSlackware',
  devuan: 'siDevuan',
  artix: 'siArtixlinux',
  'arch-linux': 'siArchlinux',
  endeavouros: 'siEndeavouros',
  garuda: 'siGarudalinux',
  cachyos: 'siCachyos',
  nixos: 'siNixos',
  gentoo: 'siGentoo',
  'void-linux': 'siVoidlinux',
  steamos: 'siSteamdeck',
  nobara: 'siNobaralinux',
  rhel: 'siRedhat',
  'rocky-linux': 'siRockylinux',
  almalinux: 'siAlmalinux',
  'almalinux-kitten': 'siAlmalinux',
  'centos-stream': 'siCentos',
  'alpine-linux': 'siAlpinelinux',
  'kali-linux': 'siKalilinux',
  'parrot-os': 'siParrotsecurity',
  tails: 'siTails',
  'qubes-os': 'siQubesos',
  'ubuntu-studio': 'siUbuntu',
  'raspberry-pi-os': 'siRaspberrypi',
}

const out = {}
const missing = []

for (const [id, name] of Object.entries(MAP)) {
  const icon = si[name]
  if (!icon) {
    missing.push(`${id} (${name})`)
    continue
  }
  out[id] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path }
}

// simple-icons carries no Microsoft brands, so Windows 11 is drawn by hand as
// the familiar four-pane mark.
out['windows-11'] = {
  title: 'Windows 11',
  hex: '#0078D4',
  path:
    'M0 3.449 9.75 2.1v9.451H0m10.949-9.602L24 0v11.4H10.949M0 12.6h9.75v9.451L0 20.699M10.949 12.6H24V24l-12.9-1.801',
}

const body = Object.keys(out)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(out[id])},`)
  .join('\n')

const file = `/* Generated by scripts/gen-logos.cjs. Do not edit by hand.
 * Source: simple-icons (CC0-1.0) plus a hand-drawn Windows 11 mark.
 * Bundled locally so the app never requests a logo at runtime. */
export interface SimpleLogo {
  title: string
  hex: string
  path: string
}

export const LOGOS: Record<string, SimpleLogo> = {
${body}
}
`

fs.mkdirSync(path.join(__dirname, '..', 'src', 'assets'), { recursive: true })
fs.writeFileSync(path.join(__dirname, '..', 'src', 'assets', 'logos.ts'), file)

console.log(`wrote ${Object.keys(out).length} logos`)
if (missing.length) console.log('missing:', missing.join(', '))
